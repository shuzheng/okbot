export type I18nKey = keyof (typeof dict)['zh'];

export function resolveUiLang(language: LanguageCode | undefined): UiLang {
  if (language === 'zh' || language === 'en') return language;
  if (typeof navigator !== 'undefined') {
    const nav = (navigator.language || '').toLowerCase();
    if (nav.startsWith('zh')) return 'zh';
  }
  return 'en';
}

export function t(lang: UiLang, key: I18nKey, vars?: Record<string, string>): string {
  let s: string = dict[lang][key] ?? dict.zh[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, v);
    }
  }
  return s;
}
